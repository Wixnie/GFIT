export function macrosForGrams(food, grams) {
  const m = grams / 100
  return {
    calories: round1(food.kcal * m),
    protein: round1(food.p * m),
    carbs: round1(food.c * m),
    fat: round1(food.f * m),
  }
}

function round1(n) {
  return Math.round(n * 10) / 10
}
